"""
Evaluation utilities for the
Malicious Botnet Traffic Detection Using Machine Learning project.

Member 4:
Evaluation, Results and Ablation
"""

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix,
)


def evaluate_model(y_test, y_pred):
    """
    Evaluate a classification model.

    Parameters
    ----------
    y_test : array-like
        True labels from the test dataset.

    y_pred : array-like
        Predicted labels generated by the model.

    Returns
    -------
    results : dict
        Main evaluation metrics.

    report : dict
        Detailed classification report.

    cm : numpy.ndarray
        Confusion matrix.
    """

    # ---------------------------------------------------------
    # 1. Input validation
    # ---------------------------------------------------------

    if len(y_test) != len(y_pred):
        raise ValueError(
            "y_test and y_pred must have the same length."
        )

    if len(y_test) == 0:
        raise ValueError(
            "y_test and y_pred cannot be empty."
        )

    # ---------------------------------------------------------
    # 2. Calculate Accuracy
    # ---------------------------------------------------------

    accuracy = accuracy_score(
        y_test,
        y_pred
    )

    # ---------------------------------------------------------
    # 3. Calculate Precision
    # ---------------------------------------------------------

    precision = precision_score(
        y_test,
        y_pred,
        average="weighted",
        zero_division=0
    )

    # ---------------------------------------------------------
    # 4. Calculate Recall
    # ---------------------------------------------------------

    recall = recall_score(
        y_test,
        y_pred,
        average="weighted",
        zero_division=0
    )

    # ---------------------------------------------------------
    # 5. Calculate F1-score
    # ---------------------------------------------------------

    f1 = f1_score(
        y_test,
        y_pred,
        average="weighted",
        zero_division=0
    )

    # ---------------------------------------------------------
    # 6. Classification Report
    # ---------------------------------------------------------

    report = classification_report(
        y_test,
        y_pred,
        output_dict=True,
        zero_division=0
    )

    # ---------------------------------------------------------
    # 7. Confusion Matrix
    # ---------------------------------------------------------

    cm = confusion_matrix(
        y_test,
        y_pred
    )

    # ---------------------------------------------------------
    # 8. Store main metrics
    # ---------------------------------------------------------

    results = {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1_score": f1
    }

    return results, report, cm